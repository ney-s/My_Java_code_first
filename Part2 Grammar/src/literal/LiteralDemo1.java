package literal;
/*什么是字面量
* 字面量：程序中的数据
* 分类
* 整数   直接写
* 小数   直接写
* 字符串 加双引号
* 字符   加单引号
* 布尔   true/false
* 空     null*/
public class LiteralDemo1 {
    static void main() {
        // 输出霸王龙的信息：霸王龙8岁，11.5公尺

        // 输出恐龙的名字
        System.out.println("霸王龙");

        // 输出恐龙的年龄
        System.out.println(8);

        // 输出恐龙的体重
        System.out.println(11.5);

        // 输出恐龙的性别
        System.out.println("公");

    }
}
